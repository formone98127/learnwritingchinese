// Derives comprehensive stroke-order rules (口訣) from stroke names + geometry.
// Usage: node scripts/gen-stroke-rules.mjs
import { readFile, readdir, writeFile } from 'node:fs/promises';
import path from 'node:path';

const BASELINE = 900;
const BOX = 1024;

const RULE_ORDER = [
  '先寫點',
  '先寫撇',
  '先橫後豎',
  '先豎後橫',
  '先撇後捺',
  '先折後撇',
  '先中間後兩邊',
  '由上而下',
  '由左而右',
  '由外而內',
  '先入後閉',
  '一橫封口',
  '後寫點',
];

async function loadOverrides() {
  const src = await readFile('data/strokeNames.ts', 'utf8');
  const map = {};
  for (const m of src.matchAll(/^\s+(\S):\s+\[([^\]]+)\]/gm)) {
    map[m[1]] = [...m[2].matchAll(/'([^']+)'/g)].map((x) => x[1]);
  }
  return map;
}

function center(median) {
  const p = median[Math.floor(median.length / 2)] ?? median[0];
  return { x: p[0], y: BASELINE - p[1] };
}

function isHeng(n) {
  return n === '橫' || (n.startsWith('橫') && !n.includes('豎') && !n.includes('折'));
}
function isShu(n) {
  return n === '豎' || (n.includes('豎') && !n.startsWith('橫'));
}
function isPie(n) {
  return n.includes('撇') && !n.includes('捺');
}
function isNa(n) {
  return n.includes('捺');
}
function isDian(n) {
  return n.includes('點');
}
function isZhe(n) {
  return /折|鉤/.test(n);
}

function deriveRules(char, names, medians) {
  const rules = new Set();
  const centers = medians.map(center);
  const n = names.length;
  if (n === 0) return [];

  if (isDian(names[0])) rules.add('先寫點');
  if (isPie(names[0]) && !isDian(names[0])) rules.add('先寫撇');

  const hi = names.findIndex(isHeng);
  const si = names.findIndex(isShu);
  if (hi >= 0 && si >= 0) {
    if (hi < si) rules.add('先橫後豎');
    else if (si < hi) rules.add('先豎後橫');
  }

  const pi = names.findIndex(isPie);
  const ni = names.findIndex(isNa);
  if (pi >= 0 && ni >= 0 && pi < ni) rules.add('先撇後捺');

  const zi = names.findIndex(isZhe);
  const pi2 = names.findIndex((name, i) => i > 0 && isPie(name));
  if (zi >= 0 && pi2 >= 0 && zi < pi2 && names[0] !== '撇') rules.add('先折後撇');

  if (isDian(names[n - 1]) || (n >= 2 && isDian(names[n - 1]) && isDian(names[n - 2])))
    rules.add('後寫點');

  if (n >= 3) {
    const cx0 = centers[0].x;
    const nearMid = Math.abs(cx0 - BOX / 2) < 180;
    const sides = centers.slice(1).filter((c) => Math.abs(c.x - cx0) > 90);
    if (nearMid && sides.length >= 2) rules.add('先中間後兩邊');
  }

  if (n >= 2) {
    let down = 0;
    let right = 0;
    let pairs = 0;
    for (let i = 0; i < n - 1; i++) {
      if (Math.abs(centers[i].y - centers[i + 1].y) > 40) {
        pairs++;
        if (centers[i].y < centers[i + 1].y) down++;
      }
      if (Math.abs(centers[i].x - centers[i + 1].x) > 40 && centers[i].x < centers[i + 1].x)
        right++;
    }
    if (pairs >= 1 && down / pairs >= 0.45) rules.add('由上而下');
    if (n >= 3 && right >= Math.ceil((n - 1) * 0.4)) rules.add('由左而右');
  }

  if (n >= 4) {
    const half = Math.ceil(n / 2);
    const avgL = centers.slice(0, half).reduce((a, c) => a + c.x, 0) / half;
    const avgR = centers.slice(half).reduce((a, c) => a + c.x, 0) / (n - half);
    if (avgR - avgL > 180) rules.add('由左而右');

    const avgT = centers.slice(0, half).reduce((a, c) => a + c.y, 0) / half;
    const avgB = centers.slice(half).reduce((a, c) => a + c.y, 0) / (n - half);
    if (avgB - avgT > 80) rules.add('由上而下');
  }

  const hasFold = names.some((name) => /折/.test(name));
  const lastHeng = isHeng(names[n - 1]) || names[n - 1] === '橫';
  if (hasFold && lastHeng && /豎|撇/.test(names[0])) {
    if (['口', '日', '目', '田', '四', '回'].includes(char)) rules.add('先入後閉');
    else rules.add('由外而內');
  }
  if (names[0] === '撇' && /折|鉤/.test(names[1] ?? '')) rules.add('由外而內');

  if (lastHeng && hasFold) {
    const inner = names.slice(1, -1).some((name) => isHeng(name) || isShu(name) || isPie(name));
    if (inner && ['口', '日', '目', '田'].includes(char)) rules.add('一橫封口');
  }
  if (char === '口') {
    rules.add('由上而下');
    rules.add('一橫封口');
  }

  if (n === 1) {
    rules.clear();
    rules.add('由左而右');
  }

  return RULE_ORDER.filter((r) => rules.has(r));
}

async function main() {
  const { classifyStroke } = await import('../lib/strokeGeometry.ts');
  const overrides = await loadOverrides();
  const files = (await readdir('assets/strokes')).filter((f) => f.endsWith('.json'));
  const all = {};

  for (const file of files.sort()) {
    const char = String.fromCodePoint(parseInt(file.replace('.json', ''), 16));
    const data = JSON.parse(await readFile(path.join('assets/strokes', file), 'utf8'));
    const strokeNames =
      overrides[char]?.length === data.strokes.length
        ? overrides[char]
        : data.medians.map((m) => classifyStroke(m));
    all[char] = deriveRules(char, strokeNames, data.medians);
  }

  const lines = [
    '// GENERATED by scripts/gen-stroke-rules.mjs — do not edit by hand.',
    '// Comprehensive stroke-order rules (口訣) derived from official stroke names + geometry.',
    'export const STROKE_RULES: Record<string, string[]> = {',
  ];
  for (const [char, rules] of Object.entries(all).sort()) {
    lines.push(`  ${JSON.stringify(char)}: ${JSON.stringify(rules)},`);
  }
  lines.push('};', '');
  await writeFile('data/strokeRules.ts', lines.join('\n'), 'utf8');

  const counts = Object.values(all).map((r) => r.length);
  console.log(
    `ok ${Object.keys(all).length} chars, rules/char: min=${Math.min(...counts)} avg=${(counts.reduce((a, b) => a + b, 0) / counts.length).toFixed(1)} max=${Math.max(...counts)}`,
  );
  for (const c of ['十', '木', '我', '河', '霜', '小', '上', '主', '春']) {
    console.log(`  ${c}: ${(all[c] ?? []).join('、')}`);
  }
}

main();
