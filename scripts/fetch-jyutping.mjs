// Extracts Jyutping (粵拼) readings for all bundled characters from
// rime-cantonese jyut6ping3.chars.dict.yaml (sorted by weight; first entry
// is the most common reading). Generates data/jyutping.ts.
// Usage: node scripts/fetch-jyutping.mjs
import { readdir, writeFile } from 'node:fs/promises';
import path from 'node:path';

const dir = path.resolve('assets/strokes');
const chars = (await readdir(dir))
  .filter((f) => f.endsWith('.json'))
  .map((f) => String.fromCodePoint(parseInt(f.replace('.json', ''), 16)));

const url = 'https://raw.githubusercontent.com/rime/rime-cantonese/main/jyut6ping3.chars.dict.yaml';
const text = await (await fetch(url)).text();

const map = {};
for (const line of text.split('\n')) {
  const m = line.match(/^(\S)\t(\S+)/);
  if (m && chars.includes(m[1]) && !(m[1] in map)) {
    map[m[1]] = m[2];
  }
}

const missing = chars.filter((c) => !(c in map));
if (missing.length) console.warn('MISSING:', missing.join(' '));

const out = `// GENERATED by scripts/fetch-jyutping.mjs — do not edit by hand.
// Readings: rime-cantonese jyut6ping3 (粵拼, most common reading per char).
export const JYUTPING: Record<string, string> = {
${Object.entries(map)
  .map(([ch, jp]) => `  '${ch}': '${jp}',`)
  .join('\n')}
};
`;
await writeFile(path.resolve('data/jyutping.ts'), out);
console.log(`Wrote ${Object.keys(map).length}/${chars.length} jyutping entries`);
